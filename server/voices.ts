export function getVoiceById(id: string): Voice | undefined {
  return VOICES_CONFIG.find((v) => v.id === id);
}

export function getFallbackVoice(originalVoice: Voice, targetProvider: 'google' | 'elevenlabs'): Voice {
  // Find a voice in targetProvider with the same gender
  const candidates = VOICES_CONFIG.filter(
    (v) => v.provider === targetProvider && v.gender === originalVoice.gender
  );
  if (candidates.length > 0) {
    // If one is recommended, pick it, otherwise pick the first
    return candidates.find((c) => c.isRecommended) || candidates[0];
  }
  // Fallback to any voice with the same gender
  return VOICES_CONFIG.find((v) => v.gender === originalVoice.gender) || VOICES_CONFIG[0];
}
